let qemuBinaryWatcherCleanup = null;

export const IS_DARWIN = false;

export const connectionState = {
  bus: null,
  connectIface: null,
  connectProps: null,
  /** Per-run stats state, keyed by domain object path (stable across rename,
   *  and the only identity a DomainEvent carries): path -> start time / last sample.
   *  Dropped when the domain stops or is undefined so the next run starts clean. */
  vmStartTimes: new Map(),
  prevVMStats: new Map(),
  /** Subscribers invoked on every libvirt DomainEvent and after (re)connect. */
  domainChangeHandlers: new Set(),
  /** Subscribers invoked on bus disconnect / error. */
  disconnectHandlers: new Set(),
  /** Subscribers invoked with the domain path on a STARTED DomainEvent. */
  domainStartedHandlers: new Set(),
  /** Subscribers invoked after each successful (re)connect that watches events. */
  connectedHandlers: new Set(),
  /** Subscribers invoked on every libvirt AgentEvent (per-domain qemu-ga lifecycle). */
  agentEventHandlers: new Set(),
  /** Per-domain AgentEvent subscriptions: domainPath -> { iface, listener }. */
  agentSubscriptions: new Map(),
  /** Per-domain proxy object cache: path -> { iface, props }. Avoids a DBus Introspect
   *  on every getDomainObjAndIface call (the introspection XML is regenerated by
   *  libvirtd on each fetch). Cleared on bus disconnect; individual entries dropped
   *  on UNDEFINED DomainEvent so deleted-then-recreated paths get a fresh proxy. */
  domainProxyCache: new Map(),
  /** Pino-compatible logger plumbed via connect(); null until connected. */
  logger: null,
  /** false (connect option): no DomainEvent listener, no QEMU-binary watcher,
   *  no restart-flag clearing, inert network reconciler, uncached VM list — for a short-lived process
   *  (the migration runner) that must not act alongside the backend. Kept
   *  across bus reconnects. */
  watchEvents: true,
};

export { vmError, unwrapVariant, unwrapDict, formatVersion, generateMAC };

/*
 * CODING-RULES §6: every libvirt DBus call
 * is bounded — 30 s, and 2 min for the lifecycle calls (starting a large VM,
 * undefining one with NVRAM are the slow ones; a guest shutdown request returns
 * at once anyway). dbus-next never settles a call libvirtd doesn't answer, so a
 * wedged daemon would otherwise hang the route, a reconciler or the migration
 * runner. A late answer still lands in libvirt; only the wait gives up.
 */
export const LIBVIRT_CALL_TIMEOUT_MS = 30_000;
export const LIBVIRT_LIFECYCLE_TIMEOUT_MS = 2 * 60_000;
const LIFECYCLE_METHODS = new Set(['Create', 'Shutdown', 'Destroy', 'Reboot', 'Undefine', 'Suspend', 'Resume']);

export function boundedLibvirt(promise, what, ms = LIBVIRT_CALL_TIMEOUT_MS) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(
      () => reject(vmError('LIBVIRT_ERROR', `libvirt did not answer ${what} within ${Math.round(ms / 1000)} s`)),
      ms,
    );
    timer.unref?.();
  });
  return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

/**
 * A DBus interface whose method calls (the capitalized members) are bounded;
 * everything else — its event-emitter side included — passes through.
 */
function boundedInterface(iface) {
  return new Proxy(iface, {
    get(target, prop, receiver) {
      const value = Reflect.get(target, prop, receiver);
      if (typeof value !== 'function' || typeof prop !== 'string' || !/^[A-Z]/.test(prop)) return value;
      return (...args) => {
        const result = value.apply(target, args);
        if (!result || typeof result.then !== 'function') return result;
        return boundedLibvirt(result, prop, LIFECYCLE_METHODS.has(prop) ? LIBVIRT_LIFECYCLE_TIMEOUT_MS : LIBVIRT_CALL_TIMEOUT_MS);
      };
    },
  });
}

/** A libvirt object's interface, bounded (introspection included). */
export async function getLibvirtInterface(path, name) {
  if (!connectionState.bus) throw vmError('NO_CONNECTION', 'Not connected to libvirt');
  const obj = await boundedLibvirt(connectionState.bus.getProxyObject('org.libvirt', path), 'introspection');
  return boundedInterface(obj.getInterface(name));
}

/**
 * Subscribe to libvirt domain lifecycle changes. The handler fires on every
 * `DomainEvent` signal from libvirt-dbus and once after each successful
 * (re)connect (so cache rebuilds happen automatically after a bus reset).
 * Subscribers added after `connect()` should run their own initial pass.
 * Returns an unsubscribe function.
 */
export function subscribeDomainChange(handler) {
  connectionState.domainChangeHandlers.add(handler);
  return () => connectionState.domainChangeHandlers.delete(handler);
}

/**
 * Subscribe to domain starts (a new QEMU process): `handler(domainPath)` on
 * every STARTED DomainEvent. Only fires with `watchEvents`. Returns an
 * unsubscribe function.
 */
export function subscribeDomainStarted(handler) {
  connectionState.domainStartedHandlers.add(handler);
  return () => connectionState.domainStartedHandlers.delete(handler);
}

/**
 * Subscribe to (re)connects: `handler()` after each successful connect that
 * watches events — the point to catch up on whatever happened while Wisp was
 * not connected. Returns an unsubscribe function.
 */
export function subscribeConnected(handler) {
  connectionState.connectedHandlers.add(handler);
  return () => connectionState.connectedHandlers.delete(handler);
}

export function subscribeDisconnect(handler) {
  connectionState.disconnectHandlers.add(handler);
  return () => connectionState.disconnectHandlers.delete(handler);
}

/**
 * Subscribe to libvirt per-domain qemu-ga lifecycle (AgentEvent signal).
 * Handler signature: (vmName, { state, reason, domainPath }).
 *   state: 0 = disconnected, 1 = connected (matches VIR_CONNECT_DOMAIN_EVENT_AGENT_LIFECYCLE_STATE_*)
 * Returns an unsubscribe function.
 */
export function subscribeAgentEvent(handler) {
  connectionState.agentEventHandlers.add(handler);
  return () => connectionState.agentEventHandlers.delete(handler);
}

function fireHandlers(handlers, label, ...args) {
  for (const h of handlers) {
    try { h(...args); } catch (err) { connectionState.logger?.warn?.({ err: err?.message || err }, `[vmManager] ${label} handler threw`); }
  }
}

function fireDomainChange() {
  fireHandlers(connectionState.domainChangeHandlers, 'domain-change');
}

function fireDisconnect() {
  fireHandlers(connectionState.disconnectHandlers, 'disconnect');
}

function fireAgentEvent(vmName, payload) {
  for (const h of connectionState.agentEventHandlers) {
    try { h(vmName, payload); } catch (err) { connectionState.logger?.warn?.({ err: err?.message || err }, '[vmManager] agent-event handler threw'); }
  }
}

/* Reconnect after the system bus connection drops: bounded exponential backoff,
 * one pending timer at a time (same shape as the containerd events reconnect). */
const RECONNECT_INITIAL_MS = 2000;
const RECONNECT_MAX_MS = 30000;
let reconnectDelayMs = RECONNECT_INITIAL_MS;
let reconnectTimer = null;
let reconnectAttempt = 0;
/** Delay of the retry currently pending, for the failure log. */
let scheduledDelayMs = null;

function scheduleReconnect() {
  if (reconnectTimer) return;
  const delay = reconnectDelayMs;
  scheduledDelayMs = delay;
  reconnectDelayMs = Math.min(reconnectDelayMs * 2, RECONNECT_MAX_MS);
  reconnectTimer = setTimeout(() => {
    reconnectTimer = null;
    reconnectAttempt += 1;
    const attempt = reconnectAttempt;
    connect().then(
      () => {
        connectionState.logger?.info?.({ attempt }, '[vmManager] reconnected to libvirt');
        clearReconnect();
      },
      (err) => {
        // connect()'s own failure path has scheduled the next attempt.
        connectionState.logger?.warn?.(
          { err: err?.message || String(err), attempt, retryInMs: reconnectTimer ? scheduledDelayMs : null },
          reconnectTimer ? '[vmManager] libvirt reconnect failed, retrying' : '[vmManager] libvirt reconnect failed',
        );
      },
    );
  }, delay);
}

function clearReconnect() {
  if (reconnectTimer) {
    clearTimeout(reconnectTimer);
    reconnectTimer = null;
  }
  reconnectDelayMs = RECONNECT_INITIAL_MS;
  reconnectAttempt = 0;
}

/**
 * A connected bus failed (dbus-next reports a dropped or closed socket as an
 * 'error', at the latest on the next write). Only the current bus drives a
 * reconnect: a bus that never finished connecting surfaces its failure as
 * connect()'s rejection, and a bus closed by disconnect() is no longer current.
 */
function handleBusError(bus, err) {
  if (bus !== connectionState.bus) return;
  connectionState.logger?.error?.({ err: err?.message || String(err) }, '[vmManager] DBus connection error, reconnecting');
  connectionState.bus = null;
  connectionState.connectIface = null;
  connectionState.connectProps = null;
  connectionState.domainProxyCache.clear();
  detachAllAgentSubscriptions();
  fireDisconnect();
  scheduleReconnect();
}

/**
 * @param {object} [logger]
 * @param {{ watchEvents?: boolean }} [opts]
 *   watchEvents false: connection and calls only — see connectionState.watchEvents.
 *   Omitted (as on a reconnect) keeps the current setting.
 */
export async function connect(logger = null, opts = {}) {
  if (logger) connectionState.logger = logger;
  if (typeof opts.watchEvents === 'boolean') connectionState.watchEvents = opts.watchEvents;
  const bus = dbus.systemBus();
  /* Attached at creation: an 'error' with no listener would crash the process. */
  bus.on('error', (err) => handleBusError(bus, err));
  /* dbus-next never settles calls pending on a dead bus, so each setup call
   * races the bus failing — a refused socket rejects instead of hanging — and
   * is bounded like every libvirt call, so a wedged libvirt-dbus fails the
   * connect (and a reconnect retries) instead of hanging it. */
  const busFailed = new Promise((_, reject) => bus.once('error', reject));
  busFailed.catch(() => {}); // a later bus error is handleBusError's; the races only need the rejection
  let obj;
  try {
    obj = await Promise.race([boundedLibvirt(bus.getProxyObject('org.libvirt', '/org/libvirt/QEMU'), 'introspection'), busFailed]);
    const props = obj.getInterface('org.freedesktop.DBus.Properties');
    await Promise.race([boundedLibvirt(props.Get('org.libvirt.Connect', 'LibVersion'), 'Get LibVersion'), busFailed]);
  } catch (err) {
    try { bus.disconnect(); } catch { /* bus may already be closed */ }
    // A failed first connect (libvirt-dbus not up yet at boot) retries on the
    // reconnect backoff, as a dropped bus does. Only with event watching: a
    // pending timer would keep the one-shot migration runner alive.
    if (connectionState.watchEvents) scheduleReconnect();
    throw err;
  }
  connectionState.bus = bus;
  connectionState.connectIface = boundedInterface(obj.getInterface('org.libvirt.Connect'));
  connectionState.connectProps = boundedInterface(obj.getInterface('org.freedesktop.DBus.Properties'));

  if (!connectionState.watchEvents) return;

  connectionState.connectIface.on('DomainEvent', (domainPath, event, _detail) => {
    if (event === 5 || event === 1) {
      connectionState.prevVMStats.delete(domainPath);
      connectionState.vmStartTimes.delete(domainPath);
    }
    if (event === 1) {
      // VIR_DOMAIN_EVENT_UNDEFINED — drop the cached proxy so a redefine with the same UUID gets a fresh one.
      connectionState.domainProxyCache.delete(domainPath);
    }
    // VIR_DOMAIN_EVENT_STARTED — a new QEMU process.
    if (event === 2) fireHandlers(connectionState.domainStartedHandlers, 'domain-started', domainPath);
    fireDomainChange();
  });

  if (!qemuBinaryWatcherCleanup) {
    qemuBinaryWatcherCleanup = watchQemuBinaries(fireDomainChange);
  }

  fireHandlers(connectionState.connectedHandlers, 'connected');
  fireDomainChange();
}

/**
 * Close the system DBus connection (e.g. on process shutdown). Does not reconnect.
 */
export function disconnect() {
  clearReconnect();
  if (qemuBinaryWatcherCleanup) {
    qemuBinaryWatcherCleanup();
    qemuBinaryWatcherCleanup = null;
  }
  /* No current bus: never connected, or a bus error already tore it down. */
  if (!connectionState.bus) return;
  detachAllAgentSubscriptions();
  const bus = connectionState.bus;
  /* Cleared first so handleBusError ignores anything this bus emits while closing. */
  connectionState.bus = null;
  try {
    bus.disconnect();
  } catch {
    // Bus may already be closed
  }
  connectionState.connectIface = null;
  connectionState.connectProps = null;
  connectionState.domainProxyCache.clear();
  fireDisconnect();
}

export async function getDomainObjAndIface(path) {
  const cached = connectionState.domainProxyCache.get(path);
  if (cached) return cached;
  if (!connectionState.bus) throw vmError('NO_CONNECTION', 'Not connected to libvirt');
  const obj = await boundedLibvirt(connectionState.bus.getProxyObject('org.libvirt', path), 'introspection');
  const entry = {
    iface: boundedInterface(obj.getInterface('org.libvirt.Domain')),
    props: boundedInterface(obj.getInterface('org.freedesktop.DBus.Properties')),
  };
  connectionState.domainProxyCache.set(path, entry);
  return entry;
}

export async function resolveDomain(name) {
  if (!connectionState.connectIface) throw vmError('NO_CONNECTION', 'Not connected to libvirt');
  try {
    const path = await connectionState.connectIface.DomainLookupByName(name);
    return unwrapVariant(path);
  } catch (err) {
    const msg = err.message || '';
    if (msg.includes('Domain not found') || msg.includes('virDomainLookupByName')) {
      throw vmError('VM_NOT_FOUND', `VM "${name}" not found`, msg);
    }
    throw vmError('LIBVIRT_ERROR', `Failed to look up VM "${name}"`, msg);
  }
}

export async function getDomainState(path) {
  const { iface } = await getDomainObjAndIface(path);
  const [code] = await iface.GetState(0);
  return { code, name: STATE_NAMES[code] ?? 'unknown' };
}

export async function getDomainXML(path, { inactive = false } = {}) {
  const { iface } = await getDomainObjAndIface(path);
  return iface.GetXMLDesc(inactive ? 2 : 0);
}

/**
 * Attach an AgentEvent listener to a per-domain DBus proxy. Idempotent: calling twice
 * for the same path replaces the prior subscription. Used by vmManagerNetwork
 * to react to qemu-ga connect/disconnect without polling.
 */
export async function attachAgentSubscription(domainPath, vmName) {
  if (!connectionState.bus) return;
  const existing = connectionState.agentSubscriptions.get(domainPath);
  if (existing && existing.vmName === vmName) return;
  if (existing) detachAgentSubscription(domainPath);

  try {
    const { iface } = await getDomainObjAndIface(domainPath);
    const listener = (state, reason) => {
      fireAgentEvent(vmName, { state, reason, domainPath });
    };
    iface.on('AgentEvent', listener);
    connectionState.agentSubscriptions.set(domainPath, { iface, listener, vmName });
  } catch (err) {
    connectionState.logger?.warn?.({ vmName, err: err?.message || err }, '[vmManager] failed to attach AgentEvent');
  }
}

export function detachAgentSubscription(domainPath) {
  const entry = connectionState.agentSubscriptions.get(domainPath);
  if (!entry) return;
  try { entry.iface.removeListener('AgentEvent', entry.listener); } catch { /* best effort */ }
  connectionState.agentSubscriptions.delete(domainPath);
}

function detachAllAgentSubscriptions() {
  for (const path of [...connectionState.agentSubscriptions.keys()]) {
    detachAgentSubscription(path);
  }
}
