#!/usr/bin/env bash
# Setup step: the stub IP + container resolv.conf used by Wisp's in-process DNS
# forwarder (backend/src/lib/mdns/linux/forwarder.js).
#
# How it works:
#   - Hold the link-local 169.254.53.53/32 on a dedicated dummy interface,
#     wisp-dns0. The wisp process binds UDP+TCP 53 on this IP (via
#     CAP_NET_BIND_SERVICE) and answers container DNS queries: `.local` names
#     go to avahi over DBus, everything else goes to the host's upstream DNS.
#   - Drop a ready-to-bind-mount resolv.conf so Wisp containers on br0
#     use the stub IP as their sole nameserver.
#
# Containers still reach it: they carry an on-link `169.254.53.53/32 dev eth0`
# route and ARP for it on the bridge segment, and Linux's weak host model means
# the host answers that ARP from br0 even though the address lives elsewhere.
#
# Why a dedicated interface rather than br0 — two failure modes, both observed:
#
#   1. Runtime-only on br0: any systemd-networkd restart (an unattended systemd
#      upgrade is enough) re-applied br0's .network and flushed the address.
#      wisp's socket stays bound to the vanished IP, so `ss` still reports it
#      listening while every container DNS query black-holes. Silent and total.
#
#   2. Declared on br0 (a drop-in on its .network unit): networkd then applies
#      the static address immediately on reconfigure while the DHCP lease takes
#      a round-trip, so br0 briefly has ONLY the link-local. avahi published
#      `<host>.local -> 169.254.53.53` in that window, then re-announced with the
#      real address, hit a name conflict and renamed the host to `<host>-2`.
#      That broke every consumer of the host's .local name. Worse than (1).
#
# On its own interface the address is independent of br0's lifecycle — DHCP
# renewals and carrier flaps cannot touch it — and avahi never sees br0 without
# a routable address. Nor can it go on the bridge's netplan definition: an
# `addresses:` entry alongside `dhcp4: true` on a bridge sends networkd into a
# reconcile loop (docs/specs/CONTAINERS.md, Local DNS).
#
# Declared, not made: the dummy device and its address are a netplan definition
# in a file of Wisp's own (DNS_STUB_NETPLAN_FILE), rendered to
# systemd-networkd, so they exist at every boot before the backend starts, with
# nothing of Wisp's creating them — wisp.service creates nothing. The address
# is part of the network being online, which wisp.service is ordered after:
# the definition is not optional, so netplan's wait-online waits for it.
# Applied with `netplan generate` and `networkctl reload`, never `netplan
# apply`, which would reconfigure the bridge too. A host that holds the former
# declaration, systemd-networkd's own files and a wait-online instance of its
# own, has them taken back.
#
# Does not touch systemd-resolved.
#
# Must run as root.
# Usage: container-dns.sh <bridge>   (network-plan.sh's BRIDGE)
set -euo pipefail

if [[ $EUID -ne 0 ]]; then
  echo "ERROR: This script must be run as root (use sudo)."
  exit 1
fi

SETUP_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=step.sh
source "$SETUP_DIR/step.sh"
step_begin
# shellcheck source=net-state.sh
source "$SETUP_DIR/net-state.sh"
# shellcheck source=container-dns-plan.sh
source "$SETUP_DIR/container-dns-plan.sh"

BRIDGE="${1:-}"
[[ -n "$BRIDGE" ]] || { echo "Usage: $0 <bridge>"; exit 1; }

echo "--- Container DNS (stub IP + resolv.conf) ---"

STUB_IP="$DNS_STUB_IP"
STUB_IFACE="$DNS_STUB_IFACE"
RESOLV_OUT="/var/lib/wisp/container-resolv.conf"
NETWORKD_DIR="/etc/systemd/network"
OLD_DROPIN_NAME="wisp-mdns-stub.conf"
# The former declaration, taken back.
FORMER_FILES=("$NETWORKD_DIR/10-${STUB_IFACE}.netdev" "$NETWORKD_DIR/10-${STUB_IFACE}.network")
FORMER_WAIT_UNIT="systemd-networkd-wait-online@${STUB_IFACE}:degraded.service"
RELOAD=0

# 1. No `[Network] Address=` drop-in for the stub on br0's own .network unit:
#    failure mode (2) above.
shopt -s nullglob
for stale in "$NETWORKD_DIR"/*.network.d/"$OLD_DROPIN_NAME"; do
  rm -f "$stale"
  changed "removed stale drop-in $stale (the stub IP no longer lives on the bridge)"
  RELOAD=1
done
shopt -u nullglob

# 2. The dummy device that carries the stub IP, with nothing else on it: no
#    IPv6 and no link-local address — every extra one is another record avahi
#    would register. The address lands with scope link (networkd does that for
#    169.254/16), which is fine: the forwarder binds it explicitly, so replies
#    to containers never go through the kernel's source-address selection. The
#    backend binds the address when it starts, so the step ends with it there.
stub_up() {
  local addrs
  addrs="$(ip -4 addr show dev "$STUB_IFACE" 2>/dev/null || true)"
  [[ "$addrs" == *"${STUB_IP}/32"* ]]
}

# The renderer is set on the definition, not for the file: a file-wide one
# would weigh on the renderer of every other file's definitions.
yaml="$(staged_file)"
cat > "$yaml" <<EOF
# Generated by Wisp container-dns.sh: the stub address of Wisp's container DNS
# forwarder, on a device of its own, off the bridge.
network:
  version: 2
  dummy-devices:
    ${STUB_IFACE}:
      renderer: networkd
      addresses: [${STUB_IP}/32]
      link-local: []
      accept-ra: false
EOF
if write_if_changed "$DNS_STUB_NETPLAN_FILE" 0600 "$yaml"; then
  changed "$DNS_STUB_NETPLAN_FILE"
  RELOAD=1
fi
for f in "${FORMER_FILES[@]}"; do
  [[ ! -e "$f" ]] || RELOAD=1
done

# Rendered by netplan, then the former files gone, then systemd-networkd
# reloaded, which runs the device from netplan's units. On a change, or when
# the address is not there (files written before networkd ran), the step waits
# until the device has its address.
if (( RELOAD )) || ! stub_up; then
  step_run 0 timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" netplan generate || fail "netplan generate failed"
  for f in "${FORMER_FILES[@]}"; do
    [[ -e "$f" ]] || continue
    remove_file "$f" || fail "cannot remove $f"
    changed "removed $f (the stub is netplan's now)"
  done
  net_call networkctl reload || fail "networkctl reload failed"
  step_run 0 timeout -k "$NET_KILL_SEC" "$(( NET_WAIT_SEC + NET_CMD_SEC ))" \
    /usr/lib/systemd/systemd-networkd-wait-online -i "${STUB_IFACE}:degraded" --timeout="$NET_WAIT_SEC" >/dev/null \
    || fail "${STUB_IFACE} did not get ${STUB_IP} from systemd-networkd within $NET_WAIT_SEC s"
  stub_up || fail "${STUB_IFACE} has no ${STUB_IP} after the reload"
  changed "systemd-networkd brought up ${STUB_IFACE} with ${STUB_IP}"
fi
if systemctl is-enabled --quiet "$FORMER_WAIT_UNIT" 2>/dev/null; then
  systemd_call disable --quiet "$FORMER_WAIT_UNIT"
  changed "$FORMER_WAIT_UNIT disabled (netplan's wait-online waits for ${STUB_IFACE})"
fi

# No copy of the stub IP on the bridge, where an earlier release held it: it
# would answer alongside wisp-dns0 and can leave the bridge on a lone
# link-local address. Nothing to do when the bridge does not exist yet.
BRIDGE_ADDRS="$(net_call ip -4 addr show dev "$BRIDGE" 2>/dev/null || true)"
if [[ "$BRIDGE_ADDRS" == *"${STUB_IP}/32"* ]]; then
  net_call ip addr del "${STUB_IP}/32" dev "$BRIDGE" || fail "cannot remove ${STUB_IP}/32 from $BRIDGE"
  changed "removed ${STUB_IP}/32 from $BRIDGE (now on ${STUB_IFACE})"
fi

# 3. A ready-to-bind-mount resolv.conf for containers. The backend's
#    resolveContainerResolvConf() returns this path for containers on a primary
#    bridge (not a VLAN sub-bridge, which has no path to the stub IP).
RESOLV="$(staged_file)"
cat > "$RESOLV" <<EOF
# Generated by Wisp container-dns.sh — bind-mounted into containers on the bridge.
nameserver ${STUB_IP}
options edns0
EOF
mkdir -p /var/lib/wisp
if write_if_changed "$RESOLV_OUT" 0644 "$RESOLV"; then changed "$RESOLV_OUT"; fi
step_done
