# Sourced by the network plan (bridge-plan.sh) and the container-dns step, as
# root; do not execute it. The container DNS stub's names, its netplan
# definition, and its refusals, made before anything changes: Wisp's container
# DNS forwarder binds port 53 on the stub address (container-dns.sh), and a
# backend that cannot fails its start.

# The stub: one home for its interface, its address and the netplan file of
# Wisp's own that declares it.
DNS_STUB_IFACE=wisp-dns0
DNS_STUB_IP=169.254.53.53
DNS_STUB_NETPLAN_FILE=/etc/netplan/90-wisp-dns0.yaml
# That file as the plan rendered and checked it, in the plan's directory: the
# container-dns step installs it as it is.
DNS_STUB_PLANNED=dns-stub.yaml

# dns_stub_render <file>: the stub's netplan definition. The renderer is set on
# the definition, not for the file: a file-wide one would weigh on the renderer
# of every other file's definitions. No IPv6 and no link-local address: each
# would be another record avahi registers.
dns_stub_render() {
  cat > "$1" <<EOF
# Generated by Wisp setup: the stub address of Wisp's container DNS forwarder,
# on a device of its own, off the bridge.
network:
  version: 2
  dummy-devices:
    ${DNS_STUB_IFACE}:
      renderer: networkd
      addresses: [${DNS_STUB_IP}/32]
      link-local: []
      accept-ra: false
EOF
}

# dns_stub_holds: whether the stub device holds its settings, read from the
# kernel: DNS_STUB_IP/32 its one address, with no IPv6 address, link-local or
# other.
dns_stub_holds() {
  local out
  out="$(net_call ip -o addr show dev "$DNS_STUB_IFACE" 2>/dev/null)" || return 1
  [[ "$(awk '{ print $3, $4 }' <<<"$out")" == "inet ${DNS_STUB_IP}/32" ]]
}
# dns_stub_wait: until the stub holds its settings, up to NET_WAIT_SEC. No
# event says so: read once a second.
dns_stub_wait() {
  local deadline=$(( SECONDS + NET_WAIT_SEC ))
  until dns_stub_holds; do
    (( SECONDS < deadline )) || return 1
    sleep 1
  done
}

# refuse_dns_stub <stage>: netplan must accept the stub's definition added to
# the host's own configuration, which it accepts (<stage>, bridge-plan.sh:
# netplan_stage, refuse_netplan_rejected). It rejects one where an operator's
# wisp-dns0 is of another kind, or a netplan without dummy-devices; once live,
# a definition it rejects fails every later generate, and netplan's generator
# at boot, which then renders no network at all.
refuse_dns_stub() {
  local out kind
  # A device of that name already there of another kind (an operator's, left
  # in the kernel after its definition went) is not taken over: systemd-networkd
  # keeps a device that exists, and the stub would never get its address.
  if [[ -e "/sys/class/net/$DNS_STUB_IFACE" ]]; then
    out="$(net_read ip -j -d link show dev "$DNS_STUB_IFACE")" || exit 1
    kind="$("${SETUP_PYTHON[@]}" "$NET_SETUP_DIR/link.py" kind <<<"$out")" || net_fail "cannot read the kind of $DNS_STUB_IFACE"
    [[ "$kind" == dummy ]] \
      || refuse NETPLAN_DNS_STUB "a device $DNS_STUB_IFACE of kind ${kind:-physical} exists, where Wisp's container DNS stub is a dummy device of that name." \
        "Nothing was changed. Remove it (ip link delete $DNS_STUB_IFACE) and any definition of it of your own, and run this again."
  fi
  netplan_stage_stub "$1"
  netplan_rejects "$1" || return 0
  refuse NETPLAN_DNS_STUB "netplan accepts this host's own configuration, but rejects it with Wisp's container DNS stub, a dummy device $DNS_STUB_IFACE in $DNS_STUB_NETPLAN_FILE, added: $NETPLAN_ERROR" \
    "Nothing was changed. Remove a definition of $DNS_STUB_IFACE of your own, or use a netplan that has" \
    "dummy-devices, and run this again."
}

# refuse_dns_port: another DNS server listening there, or on every IPv4 address
# (AdGuard Home, Pi-hole, unbound, bind9, dnsmasq), is refused. Wisp's own
# backend holding it is not another.
refuse_dns_port() {
  local listeners l local_addr pid who
  listeners="$(net_read ss -Hlnup '( sport = :53 )')" || exit 1
  listeners+=$'\n'"$(net_read ss -Hlntp '( sport = :53 )')" || exit 1
  while read -r l; do
    [[ -n "$l" ]] || continue
    local_addr="$(awk '{ for (i = 1; i <= NF; i++) if ($i ~ /:53$/) { print $i; exit } }' <<<"$l")"
    case "$local_addr" in
      # A wildcard bound to one device takes the port from the stub too (the
      # forwarder's UDP bind then fails with EADDRINUSE); [::]:53 is IPv6 only
      # and leaves it free.
      "$DNS_STUB_IP:53" | 0.0.0.0:53 | 0.0.0.0%*:53 | '*:53' | '*%'*:53) ;;
      *) continue ;;
    esac
    pid="$(grep -o 'pid=[0-9]*' <<<"$l" | head -n 1 | cut -d= -f2 || true)"
    if [[ -n "$pid" ]] && grep -q '/wisp\.service' "/proc/$pid/cgroup" 2>/dev/null; then continue; fi
    who="$(grep -o '(("[^"]*"' <<<"$l" | head -n 1 | tr -d '("' || true)"
    refuse DNS_PORT_TAKEN "${who:-a process}${pid:+ (pid $pid)} listens on $local_addr, where Wisp's container DNS forwarder" \
      "listens ($DNS_STUB_IP:53). Bind that server to the addresses it serves, not to every" \
      "address, and run this again."
  done <<<"$listeners"
}
