# Sourced by network-plan.sh, the bridge step and the journal, as root; do not
# execute it. The bridge through systemd-networkd's own files.
#   plan_networkd    00-wisp-br0.netdev and 00-wisp-br0.network (the uplink's
#                    file's settings but [Match] and [Link]), and the uplink's own
#                    file rewritten as the port's definition
#   apply_networkd   the bridge's .netdev and .network first — a bridge with no
#                    port, harmless — then the uplink's own file as the port's
#                    definition, the switch; `networkctl reload`
#   check_networkd   which file networkd now runs each link from
#   finish_networkd  nothing: the switch was the last change
#   undo_networkd    after the files are back: the bridge deleted, reloaded

# networkd_bridge_file <netdev|network>: the bridge's own files.
networkd_bridge_file() { printf '/etc/systemd/network/00-wisp-%s.%s' "$BRIDGE" "$1"; }

plan_networkd() {
  local json dropins sources why rc cid_type identity a b c d iaid
  # The uplink's own file becomes its definition as the bridge's port: the
  # same name under /etc/systemd/network — in place, or, for a vendor file
  # under /usr/lib or /lib, the networkd way of overriding it. A file under
  # /run is generated by something else, which would write it back.
  case "$UPLINK_NETFILE" in
    /etc/systemd/network/*.network) NETWORKD_PORT_FILE="$UPLINK_NETFILE" ;;
    /usr/lib/systemd/network/*.network | /lib/systemd/network/*.network)
      NETWORKD_PORT_FILE="/etc/systemd/network/${UPLINK_NETFILE##*/}" ;;
    /run/*) net_refuse "$UPLINK is run from $UPLINK_NETFILE, which something on this host generates: setup does not edit it." ;;
    *) net_refuse "$UPLINK is run from $UPLINK_NETFILE, outside systemd-networkd's own directories." ;;
  esac
  journal_root_ok "$NETWORKD_PORT_FILE" || net_refuse "$UPLINK is run from $UPLINK_NETFILE, which setup cannot record to undo."
  json="$(net_read networkctl status "$UPLINK" --json=short)" || exit 1
  # A drop-in applies to whichever file has its name: left alone, it would put
  # its settings back on the port, and moving it means editing several files
  # whose meaning depends on their order. Folded into the file by the
  # operator, it moves with the rest.
  dropins="$(json_array "$json" NetworkFileDropins || true)"
  [[ -z "${dropins//[[:space:]]/}" ]] \
    || net_refuse "$UPLINK's $UPLINK_NETFILE has drop-ins (${dropins//\"/}): fold them into the file, which setup then carries over whole."
  sources=("$UPLINK_NETFILE")
  UPLINK_CLIENT_ID="$(client_id "$UPLINK" "$NET_TOOL")"
  # The uplink's settings: its layer 3 moves to the bridge — [Network],
  # [Address], [Route] and DNS settings, its DHCP ones — with the DHCP identity
  # pinned below; its match and link settings ([Match], [Link]) stay with it, in
  # its own file, now the port's definition. Refused, naming it: a match on
  # anything but the uplink alone, a setting that ties the link to another
  # device, a section of neither kind.
  why="$(awk -v uplink="$UPLINK" -v mac="$UPLINK_MAC" -v out="$NET_PLAN_DIR/bridge.network.body" -v link_out="$NET_PLAN_DIR/port.link" -v match_out="$NET_PLAN_DIR/port.match" '
    function refuse(why) { print why; bad = 1; exit 3 }
    BEGIN {
      split("Bridge Bond VRF VLAN IPVLAN IPVTAP MACVLAN MACVTAP VXLAN Tunnel MACsec Xfrm KeepMaster " \
        "BindCarrier ActiveSlave PrimarySlave", k, " ")
      for (i in k) network_tied[k[i]] = 1
      split("Network Address Route RoutingPolicyRule NextHop DHCP DHCPv4 DHCPv6 DHCPPrefixDelegation " \
        "IPv6AcceptRA Link", s, " ")
      for (i in s) section_ok[s[i]] = 1
    }
    /^[ \t]*($|[#;])/ { next }
    /^[ \t]*\[.*\][ \t]*$/ {
      sect = $0; gsub(/^[ \t]*\[|\][ \t]*$/, "", sect)
      if (sect != "Match" && !(sect in section_ok)) refuse(FILENAME " has a [" sect "] section, which setup does not carry over to a bridge")
      if (sect == "Link") { if (!port_link++) print "\n[Link]" > link_out }
      else if (sect != "Match") { print "\n[" sect "]" > out; out_sect = sect }
      next
    }
    {
      key = $0; sub(/=.*/, "", key); gsub(/[ \t]/, "", key)
      val = $0; sub(/^[^=]*=[ \t]*/, "", val); sub(/[ \t]+$/, "", val)
      if (sect == "") refuse(FILENAME ": a setting outside any section")
      if (sect == "Match") {
        if (key == "Name") { if (val != uplink) refuse(FILENAME " matches the name \"" val "\", not " uplink " alone"); by_name = 1 }
        else if (key == "MACAddress" || key == "PermanentMACAddress") {
          if (tolower(val) != mac) refuse(FILENAME " matches " val ", not " uplink " (" mac ") alone")
          if (key == "MACAddress") by_mac = 1
        }
        else refuse(FILENAME " matches by " key)
        print $0 > match_out
        next
      }
      if (sect == "Network" && (key in network_tied)) refuse(FILENAME " sets " key " in [Network], which ties " uplink " to another device")
      if (key == "IAID") refuse(FILENAME " pins an IAID, which setup does not carry over")
      if (sect == "Network" && key == "DHCP") dhcp = val
      if ((sect == "Network" || sect == "Address") && key == "Address" && val !~ /:/) static4 = 1
      if (sect ~ /^DHCP(v4)?$/ && key == "ClientIdentifier") next
      # What the boot waits for goes with the address; the rest of the link
      # stays on the port (which only reaches "enslaved").
      if (sect == "Link" && key ~ /^Required(Family)?ForOnline$/) {
        if (out_sect != "Link") { print "\n[Link]" > out; out_sect = "Link" }
        print $0 > out
      }
      else if (sect == "Link") print $0 > link_out
      else print $0 > out
    }
    END {
      if (bad) exit 3
      # The bridge takes the uplink'"'"'s hardware address: a match on it alone
      # would take the bridge too.
      if (by_mac && !by_name) { print FILENAME " matches " uplink " by its hardware address alone, which the bridge takes too"; exit 3 }
      if (dhcp ~ /^(yes|true|on|1|ipv4|both)$/) { print "dhcp"; exit 0 }
      if (static4) { print "static"; exit 0 }
      print uplink " has neither DHCPv4 nor a static IPv4 address in " FILENAME; exit 3
    }
  ' "${sources[@]}")" || { rc=$?; if (( rc == 3 )); then net_refuse "$why."; fi; net_fail "cannot read ${sources[*]}: $why"; }
  UPLINK_MODE="$why"
  identity=""
  if [[ "$UPLINK_MODE" == dhcp ]]; then
    cid_type="${UPLINK_CLIENT_ID%%:*}"
    case "$cid_type" in
      01) identity=$'ClientIdentifier=mac\n' ;;
      ff)
        IFS=: read -r _ a b c d _ <<<"$UPLINK_CLIENT_ID"
        iaid=$((16#$a$b$c$d))
        identity=$'ClientIdentifier=duid\n'"IAID=$iaid"$'\n\n[DHCPv6]\n'"IAID=$iaid"$'\n'
        ;;
      "") net_refuse "$UPLINK is on DHCP but has no lease." ;;
      *) net_refuse "$UPLINK's DHCPv4 client identifier is of type 0x$cid_type, which setup does not carry over." ;;
    esac
  fi
  {
    echo "# Written by Wisp setup: $BRIDGE, the bridge on $UPLINK, with its hardware address."
    printf '[NetDev]\nName=%s\nKind=bridge\nMACAddress=%s\n\n[Bridge]\nSTP=no\nForwardDelaySec=0\n' "$BRIDGE" "$UPLINK_MAC"
  } > "$NET_PLAN_DIR/bridge.netdev"
  {
    echo "# Written by Wisp setup: $BRIDGE holds the address $UPLINK had, with the settings of"
    echo "# ${sources[*]}."
    printf '[Match]\nName=%s\n' "$BRIDGE"
    cat "$NET_PLAN_DIR/bridge.network.body"
    if [[ -n "$identity" ]]; then
      echo ""
      echo "# The DHCP identity $UPLINK had, so the DHCP server hands $BRIDGE the same lease."
      printf '[DHCPv4]\n%s' "$identity"
    fi
    echo ""
    echo "# The uplink's MTU, set on the bridge itself, so ports that join keep it."
    printf '[Link]\nMTUBytes=%s\n' "$UPLINK_MTU"
  } > "$NET_PLAN_DIR/bridge.network"
  rm -f "$NET_PLAN_DIR/bridge.network.body"
  {
    echo "# Written by Wisp setup: $UPLINK is $BRIDGE's port, with no addressing of its own;"
    echo "# $BRIDGE holds its address (00-wisp-$BRIDGE.network). What this file held before"
    echo "# is kept in $KEPT_DIR."
    echo "[Match]"
    cat "$NET_PLAN_DIR/port.match"
    printf '\n[Network]\nBridge=%s\nLinkLocalAddressing=no\nIPv6AcceptRA=no\n' "$BRIDGE"
    if [[ -s "$NET_PLAN_DIR/port.link" ]]; then
      cat "$NET_PLAN_DIR/port.link"
    fi
  } > "$NET_PLAN_DIR/port.network"
  rm -f "$NET_PLAN_DIR/port.link" "$NET_PLAN_DIR/port.match"
}

apply_networkd() {
  local mode=0644
  [[ -e "$NETWORKD_PORT_FILE" ]] && mode="$(stat -c %a "$NETWORKD_PORT_FILE")"
  put_file "$(networkd_bridge_file netdev)" "$NET_PLAN_DIR/bridge.netdev" 0644 || return 1
  put_file "$(networkd_bridge_file network)" "$NET_PLAN_DIR/bridge.network" 0644 || return 1
  put_file "$NETWORKD_PORT_FILE" "$NET_PLAN_DIR/port.network" "$mode" || return 1
  apply_notice
  timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" networkctl reload
}
check_networkd() {
  local link want got
  for link in "$BRIDGE" "$UPLINK"; do
    want="$(networkd_bridge_file network)"
    [[ "$link" == "$UPLINK" ]] && want="$NETWORKD_PORT_FILE"
    got="$(json_string "$(timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" networkctl status "$link" --json=short 2>/dev/null)" NetworkFile || true)"
    if [[ "$got" != "$want" ]]; then
      WHY="systemd-networkd runs $link from '${got}', not $want"
      return 1
    fi
  done
}
finish_networkd() { :; }

# undo_networkd <bridge> <uplink>: runs in journal_restore's subshell.
undo_networkd() {
  [[ ! -e "/sys/class/net/$1" ]] || timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" networkctl delete "$1"
  timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" networkctl reload \
    && timeout -k "$NET_KILL_SEC" "$NET_CMD_SEC" networkctl reconfigure "$2"
}
