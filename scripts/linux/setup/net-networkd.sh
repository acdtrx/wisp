# Sourced by network-plan.sh, the bridge step and the journal, as root; do not
# execute it. The bridge through systemd-networkd's own files.
#   plan_networkd    00-wisp-br0.netdev and 00-wisp-br0.network (the uplink's
#                    file's settings but [Match] and [Link]), and the uplink's own
#                    file rewritten as the port's definition
#   apply_networkd   the bridge's .netdev and .network first — a bridge with no
#                    port, harmless — then the uplink's own file as the port's
#                    definition, the switch; `networkctl reload`
#   check_networkd   which file networkd now runs each link from (CHECK_WHY)
#   finish_networkd  nothing: the switch was the last change
#   undo_networkd    after the files are back: the bridge deleted, reloaded

# networkd_bridge_file <netdev|network>: the bridge's own files.
networkd_bridge_file() { printf '/etc/systemd/network/00-wisp-%s.%s' "$BRIDGE" "$1"; }

# networkd_takers <own-file>: refused when another .network file could take the
# uplink (networkd.py): setup leaves exactly one definition for it.
networkd_takers() {
  local driver takers
  driver="$(basename "$(readlink "/sys/class/net/$UPLINK/device/driver" 2>/dev/null)" 2>/dev/null || true)"
  takers="$(python3 -I "$NET_SETUP_DIR/networkd.py" takers "$UPLINK" "$UPLINK_MAC" "$driver" "$1")" \
    || net_fail "cannot read systemd-networkd's files"
  [[ -z "$takers" ]] \
    || refuse NETWORKD_SECOND_FILE "systemd-networkd could take the uplink $UPLINK from $(echo $takers) too, beside $1: setup leaves exactly one definition for it. Make that file match only other interfaces, or remove it, and run this again."
  printf '%s\n' "takers none"
}

plan_networkd() {
  local dropins mode rc identity
  # The uplink's own file becomes its definition as the bridge's port: the
  # same name under /etc/systemd/network — in place, or, for a vendor file
  # under /usr/lib or /lib, the networkd way of overriding it. A file under
  # /run is generated by something else, which would write it back.
  case "$UPLINK_NETFILE" in
    /etc/systemd/network/*.network) NETWORKD_PORT_FILE="$UPLINK_NETFILE" ;;
    /usr/lib/systemd/network/*.network | /lib/systemd/network/*.network)
      NETWORKD_PORT_FILE="/etc/systemd/network/${UPLINK_NETFILE##*/}" ;;
    /run/*) refuse NETWORKD_RUN_FILE "$UPLINK is run from $UPLINK_NETFILE, which something on this host generates, so setup does not edit it: run the uplink from a file of your own under /etc/systemd/network, and run this again." ;;
    *) refuse NETWORKD_OTHER_FILE "$UPLINK is run from $UPLINK_NETFILE, outside systemd-networkd's own directories: run the uplink from a file of your own under /etc/systemd/network, and run this again." ;;
  esac
  journal_root_ok "$NETWORKD_PORT_FILE" \
    || refuse NETWORKD_OTHER_FILE "$UPLINK is run from $UPLINK_NETFILE, which setup cannot record to undo: run the uplink from a file of your own under /etc/systemd/network, and run this again."
  [[ ! -L "$UPLINK_NETFILE" ]] \
    || refuse NETWORKD_LINK_FILE "$UPLINK is run from $UPLINK_NETFILE, a symbolic link, which setup would replace with a file: make it the file itself, and run this again."
  # A drop-in applies to whichever file has its name: left alone, it would put
  # its settings back on the port, and moving it means editing several files
  # whose meaning depends on their order. Folded into the file by the
  # operator, it moves with the rest.
  dropins="$(networkd_json "$UPLINK" NetworkFileDropins)" || net_fail "cannot read systemd-networkd's status of $UPLINK"
  [[ -z "$dropins" ]] \
    || refuse NETWORKD_DROPINS "$UPLINK's $UPLINK_NETFILE has drop-ins ($(echo $dropins)): fold them into the file, which setup then carries over whole, and run this again."
  networkd_takers "$UPLINK_NETFILE" >/dev/null
  uplink_client_id
  # The uplink's file, split by networkd.py's lists: its layer 3 moves to the
  # bridge, with the DHCP identity pinned below; its match, link and layer-2
  # settings stay with it, in its own file, now the port's definition.
  mode="$(python3 -I "$NET_SETUP_DIR/networkd.py" port "$UPLINK_NETFILE" "$UPLINK" "$UPLINK_MAC" "$NET_PLAN_DIR")" \
    || { rc=$?; case $rc in
           3) net_refuse NETWORKD_SETTING "$mode." ;;
           4) net_refuse UPLINK_DEPENDENT "$mode." ;;
           5) refuse NETWORKD_SETTING "$mode: match $UPLINK by Name=$UPLINK in its [Match] (with MACAddress=$UPLINK_MAC, if wanted), and run this again." ;;
         esac; net_fail "cannot read $UPLINK_NETFILE: $mode"; }
  UPLINK_MODE="$mode"
  identity=""
  if [[ "$UPLINK_MODE" == dhcp ]]; then
    dhcp_identity
    refuse_dhcp_identity
    identity="$(dhcp_identity_networkd)"
  fi
  {
    echo "# Written by Wisp setup: $BRIDGE, the bridge on $UPLINK, with its hardware address."
    printf '[NetDev]\nName=%s\nKind=bridge\nMACAddress=%s\n\n[Bridge]\nSTP=no\nForwardDelaySec=0\n' "$BRIDGE" "$UPLINK_MAC"
  } > "$NET_PLAN_DIR/bridge.netdev"
  {
    echo "# Written by Wisp setup: $BRIDGE holds the address $UPLINK had, with the settings of"
    echo "# $UPLINK_NETFILE."
    printf '[Match]\nName=%s\n' "$BRIDGE"
    cat "$NET_PLAN_DIR/bridge.network.body"
    if [[ -n "$identity" ]]; then
      echo ""
      echo "# The DHCP identity $UPLINK had, so the DHCP server hands $BRIDGE the same lease."
      printf '%s\n' "$identity"
    fi
    echo ""
    echo "# The uplink's MTU, set on the bridge itself, so ports that join keep it."
    printf '[Link]\nMTUBytes=%s\n' "$UPLINK_MTU"
  } > "$NET_PLAN_DIR/bridge.network"
  {
    echo "# Written by Wisp setup: $UPLINK is $BRIDGE's port, with no addressing of its own;"
    echo "# $BRIDGE holds its address (00-wisp-$BRIDGE.network). What this file held before"
    echo "# is kept in $KEPT_DIR."
    echo "[Match]"
    cat "$NET_PLAN_DIR/port.match"
    printf '\n[Network]\nBridge=%s\nLinkLocalAddressing=no\nIPv6AcceptRA=no\n' "$BRIDGE"
    cat "$NET_PLAN_DIR/port.link"
  } > "$NET_PLAN_DIR/port.network"
  rm -f "$NET_PLAN_DIR/bridge.network.body" "$NET_PLAN_DIR/port.link" "$NET_PLAN_DIR/port.match"
}

# sources_networkd: what the plan read, for the bridge step to check is
# unchanged: the uplink's file, by checksum, and who else could take it.
sources_networkd() {
  local file dropins
  sha256sum "$UPLINK_NETFILE" || return 1
  file="$(networkd_json "$UPLINK" NetworkFile)" || return 1
  dropins="$(networkd_json "$UPLINK" NetworkFileDropins)" || return 1
  echo "runs-from $file $dropins"
  sources_refusals networkd_takers "$UPLINK_NETFILE" || return 1
}

apply_networkd() {
  local mode=0644
  [[ -e "$NETWORKD_PORT_FILE" ]] && mode="$(stat -c %a "$NETWORKD_PORT_FILE")"
  put_file "$(networkd_bridge_file netdev)" "$NET_PLAN_DIR/bridge.netdev" 0644 || return 1
  put_file "$(networkd_bridge_file network)" "$NET_PLAN_DIR/bridge.network" 0644 || return 1
  put_file "$NETWORKD_PORT_FILE" "$NET_PLAN_DIR/port.network" "$mode" || return 1
  apply_notice
  net_call networkctl reload
}
# networkd_runs_from <bridge's file> <uplink's file>: whether systemd-networkd
# runs the bridge and the uplink from those files (the check, on netplan too).
networkd_runs_from() {
  local link want got
  for link in "$BRIDGE" "$UPLINK"; do
    want="$1"
    [[ "$link" == "$UPLINK" ]] && want="$2"
    got="$(networkd_json "$link" NetworkFile 2>/dev/null || true)"
    if [[ "$got" != "$want" ]]; then
      CHECK_WHY="systemd-networkd runs $link from '${got}', not $want"
      return 1
    fi
  done
}
check_networkd() { networkd_runs_from "$(networkd_bridge_file network)" "$NETWORKD_PORT_FILE"; }
finish_networkd() { :; }

# undo_networkd: in journal_restore, once the files are back.
undo_networkd() {
  [[ ! -e "/sys/class/net/$BRIDGE" ]] || net_call networkctl delete "$BRIDGE" || return 1
  net_call networkctl reload && net_call networkctl reconfigure "$UPLINK"
}
